def build_messages(conversation: Conversation, checklist: Checklist) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": canonical_json(
                {
                    "checklist": checklist.model_dump(mode="json"),
                    "untrusted_transcript": conversation.model_dump(
                        mode="json", exclude={"audio_url"}
                    ),
                }
            ),
        },
    ]


def response_schema() -> dict:
    return ModelResponse.model_json_schema()
